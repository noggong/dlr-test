CATS = ["POLITICS", "CURRENT", "SOCIETY", "GENERAL"]


def sha(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def lit(s) -> str:
    return str(s) if isinstance(s, int) else "'" + s.replace("'", "''") + "'"


def build() -> list:
    rows = []
    for d in (1, 2, 3):
        for c in CATS:
            qs = Q[(c, d)]
            assert len(qs) == 25, (c, d, len(qs))
            for body, ans in qs:
                pk = sha(f"question:{c}:{d}:{body}")
                rows.append((pk, d, c, body, ans, sha(f"{pk}:{normalize(ans)}")))
    assert len(rows) == 300
    assert len({r[0] for r in rows}) == 300, "pk_hash 중복"
    assert len({r[3] for r in rows}) == 300, "본문 중복"
    for r in rows:
        # 본문 · 답에 ';' 가 있으면 Spring 스크립트 실행기가 문장을 잘못 나눈다
        assert len(r[0]) == 64 and len(r[5]) == 64 and len(r[2]) <= 10 and ";" not in r[3] + r[4], r
        assert not r[3].startswith("[시드 "), "생성 규칙 시드(data.sql)의 본문 꼴과 겹친다"
    return rows


def render_sql(rows: list) -> str:
    values = ",\n".join(
        "  (" + ", ".join(lit(v) for v in (i, pk, d, c, b, a, h)) + ")"
        for i, (pk, d, c, b, a, h) in enumerate(rows, 1)
    )
    return f"""-- ============================================================
-- 실제 문제 시드 300개 — 정본은 docs/lld/platform.md §2.2. tools/questions/gen.py 가 만든다(손으로 고치지 않는다).
-- 난이도 1 · 2 · 3 × 분야 POLITICS · CURRENT · SOCIETY · GENERAL × 25. api 의 spring.sql.init 이 data.sql 바로 뒤에 적용한다.
-- pk_hash = SHA-256(UTF-8("question:<category>:<difficulty>:<body>")) · answer_hash = SHA-256(UTF-8("<pk_hash>:<정규화한 답>"))(prd D7 · D22).
-- data.sql 과 같은 멱등: 이미 있는 pk_hash 는 NOT EXISTS 로 먼저 걸러 id 시퀀스를 쓰지 않고, 동시 기동 경합은 ON CONFLICT DO NOTHING 이 막는다.
-- ============================================================

INSERT INTO questions (pk_hash, difficulty, category, body, answer, answer_hash)
SELECT q.pk_hash, q.difficulty, q.category, q.body, q.answer, q.answer_hash
FROM (VALUES
{values}
) AS q (no, pk_hash, difficulty, category, body, answer, answer_hash)
WHERE NOT EXISTS (SELECT 1 FROM questions x WHERE x.pk_hash = q.pk_hash)
ORDER BY q.no
ON CONFLICT (pk_hash) DO NOTHING;
"""


def render_json(rows: list) -> str:
    keys = ["pk_hash", "difficulty", "category", "body", "answer", "answer_hash"]
    return json.dumps([dict(zip(keys, r)) for r in rows], ensure_ascii=False, indent=1) + "\n"


def main() -> int:
    rows = build()
    outputs = {SQL_OUT: render_sql(rows), JSON_OUT: render_json(rows)}
    if "--check" in sys.argv[1:]:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"다르다: {p.relative_to(ROOT)} — python3 -I tools/questions/gen.py 로 다시 만든다", file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8")
        print(f"썼다: {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
